  static int _jdn(DateTime d) {
    // Fliegel–Van Flandern (تقويم ميلادي ⇐ JDN) على التاريخ المحلي بلا وقت
    final a = (14 - d.month) ~/ 12;
    final y = d.year + 4800 - a;
    final m = d.month + 12 * a - 3;
    return d.day +
        (153 * m + 2) ~/ 5 +
        365 * y +
        y ~/ 4 -
        y ~/ 100 +
        y ~/ 400 -
        32045;
  }

  static DateTime _fromJdn(int jdn) {
    final a = jdn + 32044;
    final b = (4 * a + 3) ~/ 146097;
    final c = a - 146097 * b ~/ 4;
    final d = (4 * c + 3) ~/ 1461;
    final e = c - 1461 * d ~/ 4;
    final m = (5 * e + 2) ~/ 153;
    final day = e - (153 * m + 2) ~/ 5 + 1;
    final month = m + 3 - 12 * (m ~/ 10);
    final year = 100 * b + d - 4800 + m ~/ 10;
    return DateTime(year, month, day);
  }

  /// ميلادي ⇐ هجري (أم القرى). null خارج نطاق الجدول.
  static HijriDate? fromGregorian(DateTime g) {
    final jdn = _jdn(DateTime(g.year, g.month, g.day));
    final t = _monthStartsJdn;
    if (jdn < t.first || jdn >= t.last) return null;
    // بحث ثنائي عن آخر بداية شهر ≤ jdn
    var lo = 0, hi = t.length - 2;
    while (lo < hi) {
      final mid = (lo + hi + 1) >> 1;
      if (t[mid] <= jdn) {
        lo = mid;
      } else {
        hi = mid - 1;
      }
    }
    return HijriDate(firstYear + lo ~/ 12, lo % 12 + 1, jdn - t[lo] + 1);
  }

  /// هجري ⇐ ميلادي. null خارج النطاق أو يوم غير موجود في ذلك الشهر.
  static DateTime? toGregorian(HijriDate h) {
    final i = (h.year - firstYear) * 12 + h.month - 1;
    if (i < 0 || i >= _monthStartsJdn.length - 1) return null;
    final len = _monthStartsJdn[i + 1] - _monthStartsJdn[i];
    if (h.day < 1 || h.day > len) return null;
    return _fromJdn(_monthStartsJdn[i] + h.day - 1);
  }

  /// عدد أيام الشهر الهجري (29 أو 30)
  static int? monthLength(int year, int month) {
    final i = (year - firstYear) * 12 + month - 1;
    if (i < 0 || i >= _monthStartsJdn.length - 1) return null;
    return _monthStartsJdn[i + 1] - _monthStartsJdn[i];
  }

  /// ISO (yyyy-mm-dd[…]) ⇐ هجري مختصر «1448/4/19هـ»؛ '' إن تعذّر
  static String fromIso(String? iso, {bool long = false}) {
    if (iso == null || iso.length < 10) return '';
    final d = DateTime.tryParse(iso.substring(0, 10));
    if (d == null) return '';
    final h = fromGregorian(d);
    if (h == null) return '';
    return long ? h.long : h.short;
  }
