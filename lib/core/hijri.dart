/// تاريخ هجري بسيط (لا يحمل وقتًا)
class HijriDate {
  final int year;
  final int month; // 1..12
  final int day; // 1..30
  const HijriDate(this.year, this.month, this.day);

  static const monthNames = [
    'محرم',
    'صفر',
    'ربيع الأول',
    'ربيع الثاني',
    'جمادى الأولى',
    'جمادى الآخرة',
    'رجب',
    'شعبان',
    'رمضان',
    'شوال',
    'ذو القعدة',
    'ذو الحجة',
  ];

  String get monthName => monthNames[month - 1];

  /// 1448/4/19هـ
  String get short => '$year/$month/$dayهـ';

  /// 19 ربيع الثاني 1448هـ
  String get long => '$day $monthName $yearهـ';

  @override
  bool operator ==(Object other) =>
      other is HijriDate &&
      other.year == year &&
      other.month == month &&
      other.day == day;
  @override
  int get hashCode => Object.hash(year, month, day);
  @override
  String toString() => short;
}

