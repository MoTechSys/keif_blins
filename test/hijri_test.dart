  ];

  test('ميلادي ⇐ هجري يطابق أم القرى في 53 تاريخًا مرجعيًا', () {
    for (final v in vectors) {
      final h = UmmAlQura.fromGregorian(DateTime(v.$1, v.$2, v.$3));
      expect(h, HijriDate(v.$4, v.$5, v.$6), reason: '${v.$1}-${v.$2}-${v.$3}');
    }
  });

  test('العكس صحيح لكل يوم في 2000–2077 (roundtrip)', () {
    var d = DateTime(1999, 4, 17);
    final end = DateTime(2077, 11, 16);
    var n = 0;
    while (!d.isAfter(end)) {
      final h = UmmAlQura.fromGregorian(d)!;
      expect(UmmAlQura.toGregorian(h), d, reason: '$d');
      expect(h.day, inInclusiveRange(1, 30));
      expect(h.month, inInclusiveRange(1, 12));
      d = d.add(const Duration(days: 1));
      n++;
    }
    expect(n, greaterThan(28000));
  });

  test('خارج النطاق ⇐ null، والشهر 29 أو 30 يومًا', () {
    expect(UmmAlQura.fromGregorian(DateTime(1999, 4, 16)), isNull);
    expect(UmmAlQura.fromGregorian(DateTime(2077, 11, 17)), isNull);
    expect(UmmAlQura.monthLength(1445, 9), anyOf(29, 30));
    expect(UmmAlQura.toGregorian(const HijriDate(1445, 9, 31)), isNull);
  });

  test('تنسيق ISO', () {
    expect(UmmAlQura.fromIso('2024-03-11'), '1445/9/1هـ');
    expect(UmmAlQura.fromIso('2024-03-11T10:00:00'), '1445/9/1هـ');
    expect(UmmAlQura.fromIso('2024-03-11', long: true), '1 رمضان 1445هـ');
    expect(UmmAlQura.fromIso(''), '');
    expect(UmmAlQura.fromIso('garbage'), '');
    expect(UmmAlQura.fromIso('1990-01-01'), '');
  });
}
