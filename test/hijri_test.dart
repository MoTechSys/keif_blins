  const vectors = <(int, int, int, int, int, int)>[
    (2024, 3, 11, 1445, 9, 1),
    (2024, 4, 10, 1445, 10, 1),
    (2024, 6, 16, 1445, 12, 10),
    (2024, 7, 7, 1446, 1, 1),
    (2025, 3, 1, 1446, 9, 1),
    (2025, 3, 30, 1446, 10, 1),
    (2025, 6, 26, 1447, 1, 1),
    (2026, 2, 18, 1447, 9, 1),
    (2026, 9, 30, 1448, 4, 19),
    (1999, 4, 17, 1420, 1, 1),
    (2077, 11, 16, 1500, 12, 30),
    (2000, 1, 1, 1420, 9, 24),
    (2030, 12, 31, 1452, 9, 6),
    (2029, 1, 19, 1450, 9, 4),
    (2013, 7, 14, 1434, 9, 6),
    (2035, 6, 3, 1457, 3, 26),
    (2058, 5, 25, 1480, 12, 3),
    (2004, 5, 1, 1425, 3, 12),
    (2006, 7, 1, 1427, 6, 5),
    (2073, 9, 5, 1496, 9, 3),
    (2048, 1, 28, 1470, 4, 13),
    (2008, 6, 11, 1429, 6, 7),
    (2032, 10, 21, 1454, 7, 16),
    (2052, 4, 13, 1474, 8, 13),
    (2005, 3, 15, 1426, 2, 5),
    (2045, 7, 10, 1467, 8, 25),
    (2019, 4, 6, 1440, 8, 1),
    (2003, 5, 13, 1424, 3, 12),
    (2007, 9, 17, 1428, 9, 5),
    (2038, 11, 26, 1460, 10, 29),
    (2037, 7, 7, 1459, 5, 23),
    (2006, 4, 8, 1427, 3, 10),
    (2021, 8, 4, 1442, 12, 25),
    (2008, 2, 20, 1429, 2, 13),
    (2049, 6, 8, 1471, 9, 7),
    (2038, 1, 31, 1459, 12, 25),
    (2005, 4, 20, 1426, 3, 11),
